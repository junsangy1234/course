CREATE TABLE course_anchors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    anchor_type VARCHAR(20) NOT NULL,
    parent_region_name VARCHAR(100) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    latitude NUMERIC(10, 7) NOT NULL,
    longitude NUMERIC(10, 7) NOT NULL,
    radius_meters INTEGER NOT NULL,
    display_order INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_course_anchors_code UNIQUE (code),
    CONSTRAINT ck_course_anchors_type CHECK (anchor_type IN ('AREA', 'HUB')),
    CONSTRAINT ck_course_anchors_radius CHECK (radius_meters > 0),
    CONSTRAINT ck_course_anchors_display_order CHECK (display_order >= 0)
);

CREATE TABLE course_anchor_activity_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_anchor_id BIGINT NOT NULL,
    activity_category_id BIGINT NOT NULL,
    weight INTEGER NOT NULL,
    CONSTRAINT fk_course_anchor_activity_rules_anchor
        FOREIGN KEY (course_anchor_id) REFERENCES course_anchors (id) ON DELETE CASCADE,
    CONSTRAINT fk_course_anchor_activity_rules_activity_category
        FOREIGN KEY (activity_category_id) REFERENCES activity_categories (id),
    CONSTRAINT uk_course_anchor_activity_rules_anchor_category
        UNIQUE (course_anchor_id, activity_category_id)
);

CREATE TABLE course_anchor_preference_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_anchor_id BIGINT NOT NULL,
    preference_option_id BIGINT NOT NULL,
    weight INTEGER NOT NULL,
    CONSTRAINT fk_course_anchor_preference_rules_anchor
        FOREIGN KEY (course_anchor_id) REFERENCES course_anchors (id) ON DELETE CASCADE,
    CONSTRAINT fk_course_anchor_preference_rules_preference_option
        FOREIGN KEY (preference_option_id) REFERENCES preference_options (id),
    CONSTRAINT uk_course_anchor_preference_rules_anchor_option
        UNIQUE (course_anchor_id, preference_option_id)
);

CREATE INDEX idx_course_anchors_region_active_order
    ON course_anchors (parent_region_name, is_active, display_order);

CREATE INDEX idx_course_anchor_activity_rules_category_anchor
    ON course_anchor_activity_rules (activity_category_id, course_anchor_id);

CREATE INDEX idx_course_anchor_preference_rules_option_anchor
    ON course_anchor_preference_rules (preference_option_id, course_anchor_id);

