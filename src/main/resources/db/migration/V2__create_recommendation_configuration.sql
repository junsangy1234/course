CREATE TABLE preference_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    allows_multiple_selection BOOLEAN NOT NULL DEFAULT FALSE,
    display_order INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_preference_groups_code UNIQUE (code),
    CONSTRAINT ck_preference_groups_display_order CHECK (display_order >= 0)
);

CREATE TABLE preference_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    preference_group_id BIGINT NOT NULL,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    display_order INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_preference_options_group
        FOREIGN KEY (preference_group_id) REFERENCES preference_groups (id),
    CONSTRAINT uk_preference_options_group_code UNIQUE (preference_group_id, code),
    CONSTRAINT ck_preference_options_display_order CHECK (display_order >= 0)
);

CREATE TABLE activity_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    display_order INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_activity_categories_parent
        FOREIGN KEY (parent_id) REFERENCES activity_categories (id),
    CONSTRAINT uk_activity_categories_code UNIQUE (code),
    CONSTRAINT ck_activity_categories_display_order CHECK (display_order >= 0)
);

CREATE TABLE activity_search_terms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_category_id BIGINT NOT NULL,
    provider VARCHAR(20) NOT NULL,
    keyword VARCHAR(100) NOT NULL,
    search_priority INTEGER NOT NULL,
    is_fallback BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_activity_search_terms_category
        FOREIGN KEY (activity_category_id) REFERENCES activity_categories (id),
    CONSTRAINT uk_activity_search_terms_category_provider_keyword
        UNIQUE (activity_category_id, provider, keyword),
    CONSTRAINT ck_activity_search_terms_priority CHECK (search_priority >= 0)
);

CREATE TABLE activity_recommendation_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    preference_option_id BIGINT NOT NULL,
    activity_category_id BIGINT NOT NULL,
    weight INTEGER NOT NULL,
    CONSTRAINT fk_activity_recommendation_rules_preference_option
        FOREIGN KEY (preference_option_id) REFERENCES preference_options (id),
    CONSTRAINT fk_activity_recommendation_rules_activity_category
        FOREIGN KEY (activity_category_id) REFERENCES activity_categories (id),
    CONSTRAINT uk_activity_recommendation_rules_option_category
        UNIQUE (preference_option_id, activity_category_id)
);

CREATE INDEX idx_preference_options_group_active_order
    ON preference_options (preference_group_id, is_active, display_order);

CREATE INDEX idx_preference_groups_active_order
    ON preference_groups (is_active, display_order);

CREATE INDEX idx_activity_categories_parent_active_order
    ON activity_categories (parent_id, is_active, display_order);

CREATE INDEX idx_activity_search_terms_category_active_priority
    ON activity_search_terms (activity_category_id, is_active, is_fallback, search_priority);

